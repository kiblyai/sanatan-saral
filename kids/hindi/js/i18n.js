export const lang = () => (store.get().lang === 'hi' ? 'hi' : 'en');

export function t(key, vars = {}) {
  const value = STRINGS[lang()][key] ?? STRINGS.en[key] ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// For { en, hi } objects in content.js
export const pick = (obj) => obj[lang()] ?? obj.en;
